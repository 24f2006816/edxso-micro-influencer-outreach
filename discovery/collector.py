    def discover_all(self, target_niche: Optional[str] = None) -> List[InfluencerRecord]:
        """
        Discover influencers across all supported channels and repositories.
        Returns at least 50+ diverse micro-influencer profiles.
        """
        raw_data = self._get_discovery_catalog()
        records = []
        for item in raw_data:
            rec = InfluencerRecord(
                id=item["id"],
                name=item["name"],
                platform=item["platform"],
                profile_url=item["profile_url"],
                followers=item["followers"],
                engagement_rate=item["engagement_rate"],
                niche=item["niche"],
                content_themes=item.get("content_themes", []),
                email=item.get("email", "Not Found"),
                secondary_platform=item.get("secondary_platform"),
                secondary_url=item.get("secondary_url"),
                website=item.get("website"),
                audience_age=item.get("audience_age"),
                audience_gender=item.get("audience_gender"),
                audience_geography=item.get("audience_geography"),
                content_tone=item.get("content_tone", "Authentic"),
                recent_posts=item.get("recent_posts", []),
                brand_fit_score=item.get("brand_fit_score", 8.0),
                status="Discovered"
            )
            if target_niche is None or rec.niche.lower() == target_niche.lower():
                records.append(rec)
        return records

